<?php

declare(strict_types=1);

namespace App\Support;

/**
 * Розбір списку ID з query (`exclude=5,12,40`). Чиста функція без БД і HTTP.
 * Список — лише підказка («намагайся уникнути»), тому сміття мовчки пропускається і ніколи не дає помилки:
 * фронт оновлює свій список «побачених» тільки після успішної відповіді, тож 400 на поганий елемент
 * застряг би назавжди (D-18).
 */
final class IdList
{
    /** Скільки коректних ID враховуємо: удвічі більше за 100, які тримає фронт (D-18). */
    public const MAX_IDS = 200;

    /** Верхня межа кількості фрагментів, які взагалі розглядаємо (захист від гігантських рядків). */
    private const MAX_TOKENS = 1000;

    /**
     * 'exclude' з query → список унікальних ID у порядку появи. Ніколи не кидає винятків.
     *
     * @return list<int>
     */
    public static function parse(?string $raw, int $max = self::MAX_IDS): array
    {
        if ($raw === null || $raw === '') {
            return [];
        }

        // Ліміт у explode: хвіст рядка потрапляє в останній елемент разом з комами, не проходить
        // перевірку нижче і пропускається — рядок на мегабайти не розкладається на мільйони фрагментів.
        $seen = [];
        foreach (explode(',', $raw, self::MAX_TOKENS) as $part) {
            $part = trim($part);
            // Без /u: \d тоді лише ASCII-цифри (арабсько-індійські не проходять); 10 цифр вміщуються в int
            if (preg_match('/^\d{1,10}$/', $part) !== 1) {
                continue;
            }

            $seen[(int) $part] ??= true; // ключ масиву — для швидкого пошуку повторів і збереження порядку першої появи
            if (count($seen) >= $max) {
                break;
            }
        }

        return array_keys($seen);
    }
}
